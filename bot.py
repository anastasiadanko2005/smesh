bot = Bot(token=TOKEN)
dp = Dispatcher()


def numbers_keyboard():
    buttons = [InlineKeyboardButton(text=str(i), callback_data=f"quote:{i}") for i in range(1, 32)]
    rows = [buttons[i:i + 5] for i in range(0, len(buttons), 5)]
    return InlineKeyboardMarkup(inline_keyboard=rows)


@dp.message(Command("start"))
async def cmd_start(message: Message):
    await message.answer(
        "Привет! 👋\nВыбери номер цитаты от 1 до 31:",
        reply_markup=numbers_keyboard()
    )


@dp.callback_query(F.data.startswith("quote:"))
async def send_quote(callback: CallbackQuery):
    num = int(callback.data.split(":")[1])
    quote = QUOTES.get(num, "Цитата не найдена")
    await callback.message.answer(f"<b>Цитата №{num}</b>\n\n{quote}", parse_mode="HTML")
    await callback.answer()


# --- Мини веб-сервер для Render ---
class HealthHandler(BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200)
        self.send_header("Content-type", "text/plain; charset=utf-8")
        self.end_headers()
        self.wfile.write(b"Bot is alive")

    def do_HEAD(self):
        self.send_response(200)
        self.end_headers()

    def log_message(self, format, *args):
        pass


def run_web_server():
    port = int(os.environ.get("PORT", 10000))
    server = HTTPServer(("0.0.0.0", port), HealthHandler)
    server.serve_forever()


async def main():
    threading.Thread(target=run_web_server, daemon=True).start()
    print("Bot started")
    await dp.start_polling(bot)


if __name__ == "__main__":
    asyncio.run(main())
